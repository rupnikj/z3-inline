// Regenerates test/perf-suite.smt2. The output is committed and frozen: running
// this changes the suite's SHA-256 and invalidates every baseline in
// test/perf-baseline.json (perf-check.mjs then fails rather than comparing
// against different work). Usage: node tools/gen-perf-suite.mjs test/perf-suite.smt2
// Deterministic (fixed seed, no Math.random), mixed theories, every block
// isolated with push/pop so one block cannot change another's difficulty.
import { writeFileSync } from "node:fs";

let seed = 20260816;
const rnd = () => ((seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
const pick = (a) => a[Math.floor(rnd() * a.length) % a.length];

const L = ["; z3-inline performance suite - FIXED WORKLOAD, DO NOT EDIT",
  "; Generated by tools/gen-perf-suite.mjs; regenerating invalidates",
  "; every committed baseline in test/perf-baseline.json.",
  "(set-option :produce-models false)"];

let n = 0;
const blocks = 600;
while (n < blocks) {
  const kind = n % 6;
  L.push("(push)");
  if (kind === 0) {
    // linear integer arithmetic, sat
    const k = 3 + (n % 4);
    for (let i = 0; i < k; i++) L.push(`(declare-const a${i} Int)`);
    for (let i = 0; i < k - 1; i++) L.push(`(assert (< a${i} a${i + 1}))`);
    L.push(`(assert (> a0 ${n % 17}))`, `(assert (< a${k - 1} ${100 + n}))`);
  } else if (kind === 1) {
    // linear integer arithmetic, unsat
    const b = 5 + (n % 11);
    L.push("(declare-const x Int)", "(declare-const y Int)",
      `(assert (> x ${b}))`, `(assert (< y ${b - 3}))`, "(assert (> y x))");
  } else if (kind === 2) {
    // bitvectors
    const w = 8 + ((n % 3) * 8);
    L.push(`(declare-const u (_ BitVec ${w}))`, `(declare-const v (_ BitVec ${w}))`,
      `(assert (= (bvmul u v) (_ bv${(n * 7) % 200} ${w})))`,
      `(assert (bvult u v))`, `(assert (distinct u (_ bv0 ${w})))`);
  } else if (kind === 3) {
    // arrays + integers
    L.push("(declare-const arr (Array Int Int))", "(declare-const i Int)", "(declare-const j Int)",
      `(assert (= (select arr i) ${n % 23}))`, `(assert (= (select arr j) ${(n % 23) + 5}))`,
      "(assert (= i j))");
  } else if (kind === 4) {
    // small boolean pigeonhole (unsat), size kept low so the suite stays fast
    const p = 6 + (n % 3), h = p - 1;
    for (let a = 0; a < p; a++) for (let b = 0; b < h; b++) L.push(`(declare-const q${a}_${b} Bool)`);
    for (let a = 0; a < p; a++) L.push(`(assert (or ${Array.from({ length: h }, (_, b) => `q${a}_${b}`).join(" ")}))`);
    for (let b = 0; b < h; b++)
      for (let a1 = 0; a1 < p; a1++) for (let a2 = a1 + 1; a2 < p; a2++)
        L.push(`(assert (or (not q${a1}_${b}) (not q${a2}_${b})))`);
  } else {
    // uninterpreted functions + equality
    L.push("(declare-fun f (Int) Int)", "(declare-const m Int)", "(declare-const p Int)",
      `(assert (= (f m) ${n % 13}))`, `(assert (= (f p) ${(n % 13) + 1}))`,
      `(assert (= m p))`);
  }
  L.push("(check-sat)", "(pop)");
  n++;
}
L.push("(exit)");
writeFileSync(process.argv[2], L.join("\n") + "\n");
console.log(`wrote ${process.argv[2]}: ${blocks} check-sat blocks, ${L.length} lines`);
void pick;
